import os.path
from pathlib import Path
from typing import Any

from .checksums import validate_checksum
from .crypto import convert_pem_to_der


def _expanded_destination(destination: str) -> Path:
    """
    Expand user, variables and navigation parts of a destination directory.
    """
    return Path(os.path.normpath(os.path.expandvars(Path(destination).expanduser())))


def _write_file(path: str, binary: bytes, destination: str | None = None) -> str:
    if destination:
        path = str(_expanded_destination(destination) / path)
    with Path(path).open("wb") as stream:
        stream.write(binary)
    return path


def get_certs_path(output: str, conf: dict[str, Any] | None = None, destination: str | None = None) -> tuple[str, str]:
    """
    Get paths of certificate files generated by this module.
    """
    if not conf:
        conf = {}

    filenames = conf.get("filenames", {})
    if not destination:
        destination = conf.get("destination")

    private_key_path = filenames.get("private_key", "%s.key.pem") % output
    certificate_path = filenames.get("certificate", "%s.pem") % output

    if destination:
        expanded_destination = _expanded_destination(destination)
        private_key_path = str(expanded_destination / private_key_path)
        certificate_path = str(expanded_destination / certificate_path)

    return certificate_path, private_key_path


def write_files(
    response: dict[str, Any],
    output: str,
    conf: dict[str, Any] | None = None,
    destination: str | None = None,
    *,
    der: bool = False,
    csr: bool = False,
    append_ca_certificate: bool = False,
    client: Any = None,
    verify_checksum: bool = True,
) -> dict[str, str]:
    """
    Write files contained in response.

    :param response:
    :param output:
    :type output: str
    :param der:
    :param csr:
    :param conf:
    :param append_ca_certificate:
    :param destination:
    :param client:
    """
    if not conf:
        conf = {}

    certificate_der = None
    certificate_request_der = None

    should_verify_certificate_der = True

    filenames = conf.get("filenames", {})
    if not destination:
        destination = conf.get("destination")

    generated: dict[str, str] = {}
    if "private_key" in response:
        private_key = response["private_key"].encode("ascii")
        generated["private_key"] = _write_file(
            filenames.get("private_key", "%s.key.pem") % output, private_key, destination=destination
        )

    if "certificate" in response:
        certificate = response["certificate"].encode("ascii")
        certificate_der = convert_pem_to_der("certificate", certificate)
        if verify_checksum:
            validate_checksum("certificate", certificate_der, response["sums"]["certificate"], content_is_der=True)

        if append_ca_certificate and client:
            info = client.info("")

            ca_cert = info["certificate"] + "\n"

            certificate += ca_cert.encode("ascii")
            certificate_der = convert_pem_to_der("certificate", certificate)
            should_verify_certificate_der = False

        generated["certificate"] = _write_file(
            filenames.get("certificate", "%s.pem") % output, certificate, destination=destination
        )
    if csr and "certificate_request" in response:
        certificate_request_der = convert_pem_to_der(
            "certificate_request", response["certificate_request"].encode("ascii")
        )
        if verify_checksum:
            validate_checksum(
                "certificate_request",
                certificate_request_der,
                response["sums"]["certificate_request"],
                content_is_der=True,
            )
        generated["certificate_request"] = _write_file(
            filenames.get("certificate_request", "%s.csr.pem") % output,
            response["certificate_request"].encode("ascii"),
            destination=destination,
        )

    if der:
        if certificate_der is not None:
            certificate_der_path = _write_file(
                filenames.get("certificate_der", "%s.der") % output, certificate_der, destination=destination
            )
            generated["certificate_der"] = certificate_der_path
            if verify_checksum and should_verify_certificate_der:
                with Path(certificate_der_path).open("rb") as der_file:
                    content = der_file.read()
                    validate_checksum("certificate", content, response["sums"]["certificate"], content_is_der=True)
        if certificate_request_der is not None:
            certificate_request_der_path = _write_file(
                filenames.get("certificate_request_der", "%s.csr.der") % output,
                certificate_request_der,
                destination=destination,
            )
            generated["certificate_request_der"] = certificate_request_der_path
            if verify_checksum:
                with Path(certificate_request_der_path).open("rb") as der_file:
                    content = der_file.read()
                    validate_checksum(
                        "certificate_request", content, response["sums"]["certificate_request"], content_is_der=True
                    )
    return generated


def write_stdout(
    response: dict[str, Any],
    *,
    der: bool = False,
    csr: bool = False,
    append_ca_certificate: bool = False,
    client: Any = None,
) -> None:
    """
    Writes certificates to stdout.

    :param response:
    :param der:
    :param csr:
    :param append_ca_certificate:
    :param client:
    :return:
    """
    if "private_key" in response:
        print(response["private_key"])
    if "certificate" in response:
        print(response["certificate"])

        if append_ca_certificate and client:
            info = client.info("")
            ca_cert = info["certificate"] + "\n"
            print(ca_cert)

    if "certificate_request" in response:
        print(response["certificate_request"])

    if der:
        if "certificate" in response:
            print(convert_pem_to_der("certificate", response["certificate"].encode("ascii")))
        if csr and "certificate_request" in response:
            print(convert_pem_to_der("certificate_request", response["certificate_request"].encode("ascii")))
